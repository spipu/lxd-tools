#!/bin/bash

showMessage " > Clean /etc/hosts file"

for LXD_CLEAN_IP in $(echo "$LXD_IP $LXD_INFO_IP" | tr ' ' '\n' | sort -u); do
    showMessage "  - $LXD_CLEAN_IP"
    LXD_IP_PATTERN=$(echo "$LXD_CLEAN_IP" | sed 's/\./\\./g')
    sudo sed -i "/^$LXD_IP_PATTERN .* # Generated by lxd-deploy\$/d" /etc/hosts
done

for LXD_HOST in ${LXD_HOSTS[@]}; do
    showMessage "  - $LXD_HOST"
    LXD_HOST_PATTERN=$(echo "$LXD_HOST" | sed 's/\./\\./g')
    sudo sed -i "/ $LXD_HOST_PATTERN # Generated by lxd-deploy\$/d" /etc/hosts
done
