#!/bin/bash
set -e

LXD_MODE="start"

SCRIPT_DIR=`dirname "$(readlink -f $0)"`
source ${SCRIPT_DIR}/include/init.sh

showWarning "Start the following container"
showResume

if [ ! -d "$LXD_FOLDER" ]; then
    showError "The asked container does not exist"
fi

LXD_STATUS=$(sudo lxc list "^$LXD_NAME\$" --format csv -c s)
if [[ "$LXD_STATUS" == "RUNNING" ]]; then
    showError "The asked container is already running"
fi

showWarning "Started"

showMessage " > Start Container"
sudo lxc start $LXD_NAME

source $INCLUDE_DIR/common/wait-ip.sh

source $INCLUDE_DIR/common/read-lxd-info.sh

showMessage " > Update /root/lxd-info"
if [[ "$LXD_INFO_IP" ]]; then
    sudo lxc exec $LXD_NAME -- sed -i "s/^ip=.*/ip=$LXD_IP/" /root/lxd-info
else
    sudo lxc exec $LXD_NAME -- sh -c "echo \"ip=$LXD_IP\" >> /root/lxd-info" > /dev/null
fi

source $INCLUDE_DIR/common/clean-etc-hosts-entries.sh

showMessage " > Add entries in /etc/hosts"
for LXD_HOST in ${LXD_HOSTS[@]}; do
    showMessage "  - $LXD_HOST"
    sudo sh -c "echo \"$LXD_IP $LXD_HOST # Generated by lxd-deploy\" >> /etc/hosts"
done

source $INCLUDE_DIR/common/clean-knowhosts-ip.sh
source $INCLUDE_DIR/common/add-ip-to-knowhosts.sh

showMessage " > Container List"
sudo lxc list -c ns4tS

showWarning "Finished"
